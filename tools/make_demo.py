"""Build a fake log tree so LogSeeker can be demoed without touching a real server.

    python tools/make_demo.py
    streamlit run streamlit_app.py

Writes sample logs under ./demo_logs and a .streamlit/secrets.toml pointing the
app at them through the `local` backend. Refuses to overwrite an existing
secrets.toml.
"""

from __future__ import annotations

import random
import sys
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEMO_LOGS = ROOT / "demo_logs"
SECRETS = ROOT / ".streamlit" / "secrets.toml"

INSTANCES = ["APIA", "APIE"]
SIDES = ["BUY", "SELL"]
SYMBOLS = ["0005.HK", "0700.HK", "9988.HK", "1299.HK", "0388.HK"]


def make_logs(days: int = 5, lines_per_file: int = 4000) -> list[str]:
    rng = random.Random(20260421)
    order_ids = [str(540000000 + i) for i in range(1, 41)]
    made = []

    today = date.today()
    for back in range(days):
        day = today - timedelta(days=back)
        if day.weekday() >= 5:
            continue
        stamp = day.strftime("%Y%m%d")
        for instance in INSTANCES:
            log_dir = DEMO_LOGS / "apps" / "k" / "algologs" / "ap" / instance / "logs"
            log_dir.mkdir(parents=True, exist_ok=True)
            for shard in (1, 2):
                path = log_dir / f"APA{shard}_pingOrderStream_{stamp}_{shard}.out"
                with path.open("w", encoding="utf-8") as fh:
                    for n in range(lines_per_file):
                        oid = rng.choice(order_ids)
                        fh.write(
                            f"{stamp} {n // 60:02d}:{n % 60:02d}:{rng.randint(0,59):02d}.{rng.randint(0,999):03d} "
                            f"[{instance}] pingOrderStream seq={n} orderId={oid} "
                            f"side={rng.choice(SIDES)} sym={rng.choice(SYMBOLS)} "
                            f"qty={rng.randrange(100, 100000, 100)} "
                            f"px={rng.uniform(5, 500):.3f} status=ACK\n"
                        )
                made.append(str(path))
    return sorted(order_ids)


def write_secrets() -> None:
    if SECRETS.exists():
        print(f"! {SECRETS} already exists — leaving it alone.")
        print("  Delete it first if you want the demo configuration.")
        return
    SECRETS.parent.mkdir(parents=True, exist_ok=True)
    base = (DEMO_LOGS / "apps" / "k" / "algologs" / "ap").as_posix()
    SECRETS.write_text(
        "# Generated by tools/make_demo.py — demo only, not a real deployment.\n"
        "# Delete this file before configuring LogSeeker for a real log host.\n"
        'backend = "local"\n'
        f'log_dir_template = "{base}/{{instance}}/logs"\n'
        'log_glob_template = "APA*_pingOrderStream_{date}*.out"\n'
        f"instances = {INSTANCES!r}\n".replace("'", '"')
        + "workers = 2\n"
          "cache_ttl_hours = 1\n",
        encoding="utf-8",
    )
    print(f"+ wrote {SECRETS}")


if __name__ == "__main__":
    if sys.platform == "win32":
        print("Note: the `local` backend shells out with `grep`, which on Windows means")
        print("running the app from Git Bash / WSL, or having grep on PATH.\n")
    ids = make_logs()
    print(f"+ wrote demo logs under {DEMO_LOGS}")
    print(f"  try order ids: {', '.join(ids[:6])} …")
    write_secrets()
    print("\nNow run:  streamlit run streamlit_app.py")
